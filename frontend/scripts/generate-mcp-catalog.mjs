// Writes api/_lib/mcp-catalog.mjs — the template descriptions the MCP server (api/mcp.mjs)
// answers from — out of the site's own copy, src/app/features/templates/data/template-seo.data.ts,
// so the two never drift. Run after changing that file:
//
//   node scripts/generate-mcp-catalog.mjs           write the catalog
//   node scripts/generate-mcp-catalog.mjs --check   fail if the catalog is out of date (used by tests)
//
// Prices are not stored here: the server reads them live from the API.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'src/app/features/templates/data/template-seo.data.ts');
const OUT = join(ROOT, 'api/_lib/mcp-catalog.mjs');

export async function buildCatalog() {
  const js = ts.transpileModule(readFileSync(SOURCE, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const { TEMPLATE_SEO } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
  const templates = TEMPLATE_SEO.map((t) => ({
    id: t.slotId,
    slug: t.slug,
    style: t.label,
    communities: [...t.communities],
    summary: t.summary,
    description: t.paragraphs.join('\n\n'),
    highlights: [...t.highlights],
    keywords: [...t.keywords],
  }));
  return `// Generated by scripts/generate-mcp-catalog.mjs from template-seo.data.ts. Do not edit.\nexport default ${JSON.stringify({ templates }, null, 2)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = await buildCatalog();
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
    if (current !== next) {
      console.error('api/_lib/mcp-catalog.mjs is out of date: run node scripts/generate-mcp-catalog.mjs');
      process.exit(1);
    }
    console.log('mcp-catalog.mjs is up to date');
  } else {
    writeFileSync(OUT, next);
    console.log(`Wrote ${OUT}`);
  }
}
